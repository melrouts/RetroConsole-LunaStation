"""V6 lid geometry from the V5 meshes (the V5 case is used unchanged).

Writes lid_v6_geometry.scad with:
* outline_pts: outer contour of the lid plate (section at Z 137), used for the
  45-degree edge chamfer;
* frame_pts: the LED-matrix frame walls under the lid, a ring around the
  32x32 window (polygons with holes as [outer, holes...]) clipped to the space that is free in the closed case (case
  walls and magnet posts at Z 24-30 and the lid's locating lip, minus CLEARANCE).

Also checks that the insert bosses and board stops in gamepad_lid_v6.scad fit
the free space. Needs trimesh and shapely.
"""
from pathlib import Path

import trimesh
from shapely.geometry import MultiLineString, Point, Polygon, box
from shapely.ops import polygonize, unary_union

ROOT = Path(__file__).resolve().parent
V5 = ROOT.parent / "v5"
LID_DROP = -105.0                # lid Z 135 sits on the case top Z 30
WINDOW = (0.0, 28.75)
WINDOW_HALF = 16.0
FRAME_WALL = 2.0
FRAME_R = 1.0                    # outer corner radius of the frame ring
CLEARANCE = 0.6
# Must match gamepad_lid_v6.scad.
BOSS_PITCH = (40.0, 24.0)
BOSS_D = 6.5
STOP_D = 4.0
STOP_POS = [(-18.5, 0.0), (18.5, 0.0), (0.0, -18.5)]   # relative to the window centre


def section(mesh, z):
    s = mesh.section([0, 0, 1], [0, 0, z])
    rings = polygonize(MultiLineString([[tuple(p[:2]) for p in d] for d in s.discrete]))
    area = None
    for r in rings:
        r = Polygon(r.exterior)
        area = r if area is None else area.symmetric_difference(r)
    return area


def ring_pts(coords):
    return "[" + ",".join(f"[{x:.3f},{y:.3f}]" for x, y in list(coords)[:-1]) + "]"


def pts(poly):
    return ring_pts(poly.exterior.coords)


def poly_list(polys):
    return "[" + ",".join("[" + ",".join([ring_pts(p.exterior.coords)] + [ring_pts(h.coords) for h in p.interiors])
                          + "]" for p in polys) + "]"


def main():
    lid = trimesh.load(V5 / "gamepad_lid_v5_base.stl")
    case = trimesh.load(V5 / "gamepad_case_v5.stl")

    plate = section(lid, 137.0)
    outline = Polygon(max(getattr(plate, "geoms", [plate]), key=lambda g: g.area).exterior).simplify(0.01)

    obstacles = unary_union([section(case, z) for z in (24, 25, 26, 27, 28, 29, 29.9)]
                            + [section(lid, z) for z in (131.2, 133, 134.9)])
    free = box(-45, -5, 45, 62).difference(obstacles)
    cx, cy = WINDOW
    free = [g for g in getattr(free, "geoms", [free]) if g.contains(Point(cx, cy))][0]
    safe = free.buffer(-CLEARANCE)

    outer = box(cx - WINDOW_HALF - FRAME_WALL + FRAME_R, cy - WINDOW_HALF - FRAME_WALL + FRAME_R,
                cx + WINDOW_HALF + FRAME_WALL - FRAME_R, cy + WINDOW_HALF + FRAME_WALL - FRAME_R).buffer(FRAME_R)
    window = box(cx - WINDOW_HALF, cy - WINDOW_HALF, cx + WINDOW_HALF, cy + WINDOW_HALF)
    # Opening (shrink, grow) drops slivers where the window meets the magnet post.
    ring = outer.intersection(safe).difference(window).buffer(-0.5, join_style=2).buffer(0.5, join_style=2)
    ring = [g.simplify(0.01) for g in getattr(ring, "geoms", [ring]) if g.area > 1]

    bosses = [(cx + sx * BOSS_PITCH[0] / 2, cy + sy * BOSS_PITCH[1] / 2) for sx in (-1, 1) for sy in (-1, 1)]
    for name, centres, d in (("boss", bosses, BOSS_D), ("stop", [(cx + x, cy + y) for x, y in STOP_POS], STOP_D)):
        for c in centres:
            gap = safe.exterior.distance(Point(c)) - d / 2
            if not safe.contains(Point(c).buffer(d / 2)):
                raise SystemExit(f"{name} at {c} collides with the case (margin {gap:.2f} mm)")
            print(f"{name} {c}: {gap + CLEARANCE:.2f} mm to the case/lip")

    (ROOT / "lid_v6_geometry.scad").write_text(
        "// Generated by prepare_lid_v6.py from the V5 meshes. Do not edit.\n"
        f"function outline_pts() = {pts(outline)};\n"
        f"function frame_pts() = {poly_list(ring)};\n")
    print(f"lid_v6_geometry.scad: outline {len(outline.exterior.coords)} pts, frame "
          + ", ".join(f"{g.area:.1f} mm2 {[round(b, 2) for b in g.bounds]} holes={len(g.interiors)}" for g in ring))


if __name__ == "__main__":
    main()
